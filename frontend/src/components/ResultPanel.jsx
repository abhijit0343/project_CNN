// components/ResultPanel.jsx
import React, { useState } from 'react';
import { Download, Printer, ShieldAlert } from 'lucide-react';
import { CLASSES, CLASS_METADATA } from '../data/model';
import GradCamHeatmapViewer from './GradCamHeatmapViewer';

export default function ResultPanel({ result }) {
  const [downloaded, setDownloaded] = useState(false);
  const metadata = CLASS_METADATA[result.prediction] || CLASS_METADATA.glioma;
  const isHealthy = result.prediction === 'notumor';

  const downloadReport = () => {
    const scores = result.all_scores || {};
    const timestamp = new Date(result.timestamp).toUTCString();

    const reportLines = [
      '================================================================================',
      '                        NEUROSCAN AI — CLINICAL RESEARCH REPORT                ',
      '================================================================================',
      `Date & Time        : ${timestamp}`,
      `File Identifier    : ${result.filename}`,
      `Execution Mode     : ${result.mode.toUpperCase()}`,
      `Neural Backbone    : ${result.model_used}`,
      '--------------------------------------------------------------------------------',
      'DIAGNOSTIC CLASSIFICATION SUMMARY',
      '--------------------------------------------------------------------------------',
      `Predicted Category : ${metadata.name.toUpperCase()}`,
      `Model Confidence   : ${(result.confidence * 100).toFixed(2)}%`,
      `Clinical Status    : ${isHealthy ? 'BENIGN / NORMAL ANATOMY' : 'PATHOLOGY IDENTIFIED'}`,
      `Risk Assessment    : ${metadata.riskLevel.toUpperCase()}`,
      '',
      'PATHOLOGICAL DESCRIPTION:',
      metadata.description,
      '',
      'CLINICAL RADIOLOGY NOTE:',
      metadata.clinicalNote,
      '--------------------------------------------------------------------------------',
      'SOFTMAX CLASS PROBABILITY DISTRIBUTION',
      '--------------------------------------------------------------------------------',
      ...CLASSES.map((cls) => {
        const prob = Number(scores[cls] || 0);
        const bar = '■'.repeat(Math.round(prob * 30)).padEnd(30, ' ');
        return `${CLASS_METADATA[cls].name.padEnd(20, ' ')} : ${(prob * 100).toFixed(2).padStart(6, ' ')}%  [${bar}]`;
      }),
      '--------------------------------------------------------------------------------',
      'MODEL ARCHITECTURAL STAGES',
      '--------------------------------------------------------------------------------',
      '01. Input Tensor               : 224 x 224 x 3 (ImageNet Normalized)',
      '02. Stem Conv3x3               : 112 x 112 x 32',
      '03. Inverted Residuals (MBConv): Stages 1-7 (16 to 320 feature channels)',
      '04. Global Average Pooling     : 1280 feature vector',
      '05. Classifier Head            : Linear(1280 -> 256) -> ReLU -> Linear(128) -> Linear(4)',
      '06. Saliency Attribution       : Grad-CAM backpropagated to Stage 7 (Pointwise 1280)',
      '================================================================================',
      'RESEARCH & EDUCATIONAL DISCLAIMER:',
      'This analysis was generated by a deep convolutional neural network for research',
      'and educational purposes. It DOES NOT constitute a formal radiological diagnosis,',
      'medical opinion, or treatment recommendation. All scans must be evaluated by',
      'a board-certified radiologist or neurosurgeon.',
      '================================================================================',
    ];

    const blob = new Blob([reportLines.join('\n')], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.download = `neuroscan-report-${result.filename.replace(/\.[^/.]+$/, '')}.txt`;
    link.click();
    URL.revokeObjectURL(url);

    setDownloaded(true);
    setTimeout(() => setDownloaded(false), 3000);
  };

  const triggerPrint = () => {
    window.print();
  };

  return (
    <div className="space-y-6 animate-in fade-in slide-in-from-bottom-3 duration-500">
      {/* Primary Result Banner Card */}
      <div className="bg-[#FBFCFA] border border-[#DCE3E2] p-6 sm:p-8 shadow-sm">
        {/* Top Header */}
        <div className="flex flex-wrap items-center justify-between gap-4 pb-4 border-b border-[#E3EAE9]">
          <div>
            <span className="font-mono text-[10px] tracking-widest uppercase text-[#778995] font-semibold">
              03 / DIAGNOSTIC CLASSIFICATION
            </span>
            <div className="flex items-center gap-2 mt-1">
              <span className="text-xs font-mono text-[#526D7C]">Scan ID:</span>
              <span className="text-xs font-mono font-bold text-[#003153]">{result.filename}</span>
              <span
                className={`text-[9px] font-mono px-2 py-0.5 rounded-sm uppercase tracking-wider font-bold ${
                  result.mode === 'live'
                    ? 'bg-emerald-50 text-emerald-800 border border-emerald-300'
                    : 'bg-amber-50 text-amber-800 border border-amber-300'
                }`}
              >
                ● {result.mode === 'live' ? 'LIVE MODEL INFERENCE' : 'SIMULATION MODE'}
              </span>
            </div>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={downloadReport}
              className="inline-flex items-center gap-2 px-3.5 py-2 text-xs font-mono font-semibold text-[#003153] bg-white border border-[#CBD8D9] hover:border-[#D62839] hover:text-[#D62839] transition-colors"
            >
              <Download className="w-3.5 h-3.5" />
              {downloaded ? 'Downloaded ✓' : 'Download Dossier'}
            </button>
            <button
              onClick={triggerPrint}
              className="inline-flex items-center gap-2 px-3 py-2 text-xs font-mono font-semibold text-[#526D7C] bg-white border border-[#CBD8D9] hover:bg-[#F2F6F5] transition-colors"
              title="Print Clinical Summary"
              aria-label="Print Clinical Summary"
            >
              <Printer className="w-3.5 h-3.5" />
            </button>
          </div>
        </div>

        {/* Diagnosis & Probability Grid */}
        <div className="grid grid-cols-1 lg:grid-cols-[1.1fr_1.3fr] gap-8 py-6">
          {/* Left Column: Big Classification & Confidence */}
          <div className="space-y-5 lg:pr-6 lg:border-r border-[#E3EAE9]">
            <div>
              <span className="text-[10px] font-mono uppercase tracking-widest text-[#718590] block mb-1">
                PREDICTED CATEGORY
              </span>
              <h3
                className={`text-4xl sm:text-5xl font-display tracking-tight ${
                  isHealthy ? 'text-[#003153]' : 'text-[#D62839]'
                }`}
              >
                {metadata.name}
              </h3>
              <p className="text-xs text-[#526D7C] leading-relaxed mt-2 max-w-md">
                {metadata.description}
              </p>
            </div>

            {/* Confidence Gauge */}
            <div className="bg-[#F2F6F5] border border-[#DEE6E5] p-4">
              <div className="flex items-baseline justify-between mb-2">
                <span className="text-[10px] font-mono uppercase tracking-wider text-[#637987]">
                  Model Confidence
                </span>
                <span className="font-mono text-2xl font-bold text-[#003153]">
                  {(result.confidence * 100).toFixed(2)}
                  <span className="text-sm font-normal text-[#637987]">%</span>
                </span>
              </div>
              <div className="w-full h-2 bg-[#DCE4E3] rounded-full overflow-hidden">
                <div
                  className={`h-full transition-all duration-1000 ${
                    isHealthy ? 'bg-[#003153]' : 'bg-[#D62839]'
                  }`}
                  style={{ width: `${Math.min(100, result.confidence * 100)}%` }}
                />
              </div>
              <div className="flex justify-between items-center text-[9px] font-mono text-[#778B96] mt-2">
                <span>Decision Threshold: 0.50</span>
                <span>Calibrated Softmax Output</span>
              </div>
            </div>

            {/* Clinical Impression Note */}
            <div className="p-3 bg-white border border-[#DEE6E5] text-[11px] text-[#425969] leading-relaxed">
              <b className="text-[#003153] block mb-1 uppercase font-mono text-[9px] tracking-wider">
                Radiological Recommendation:
              </b>
              {metadata.clinicalNote}
            </div>
          </div>

          {/* Right Column: All Class Probability Distribution */}
          <div className="space-y-4">
            <div className="flex justify-between items-center pb-2 border-b border-[#E3EAE9]">
              <span className="text-[10px] font-mono uppercase tracking-widest text-[#718590]">
                FOUR-CLASS PROBABILITY DISTRIBUTION
              </span>
              <span className="text-[9px] font-mono text-[#8C9FA9]">
                SUM = 1.0 (SOFTMAX)
              </span>
            </div>

            <div className="space-y-3 pt-1">
              {CLASSES.map((cls) => {
                const prob = Number(result.all_scores?.[cls] || 0);
                const isWinner = cls === result.prediction;
                const classMeta = CLASS_METADATA[cls];

                return (
                  <div
                    key={cls}
                    className={`p-3 rounded-none border transition-all ${
                      isWinner
                        ? 'bg-[#F2F6F5] border-[#003153] shadow-sm'
                        : 'bg-white border-[#E3EAE9] opacity-80 hover:opacity-100'
                    }`}
                  >
                    <div className="flex items-center justify-between text-xs mb-1.5">
                      <div className="flex items-center gap-2">
                        <span
                          className={`w-2 h-2 rounded-full ${
                            isWinner
                              ? cls === 'notumor'
                                ? 'bg-[#003153]'
                                : 'bg-[#D62839]'
                              : 'bg-[#CBDCDF]'
                          }`}
                        />
                        <span className={`font-semibold ${isWinner ? 'text-[#003153]' : 'text-[#526D7C]'}`}>
                          {classMeta.name}
                        </span>
                        {isWinner && (
                          <span className="text-[8px] font-mono px-1.5 py-0.2 rounded-sm bg-[#003153] text-white">
                            PREDICTED
                          </span>
                        )}
                      </div>
                      <span className="font-mono text-xs font-bold text-[#003153]">
                        {(prob * 100).toFixed(2)}%
                      </span>
                    </div>

                    <div className="w-full h-1.5 bg-[#E8EFF0] rounded-full overflow-hidden">
                      <div
                        className={`h-full transition-all duration-700 ${
                          isWinner
                            ? cls === 'notumor'
                              ? 'bg-[#003153]'
                              : 'bg-[#D62839]'
                            : 'bg-[#8CA2AE]'
                        }`}
                        style={{ width: `${Math.min(100, prob * 100)}%` }}
                      />
                    </div>
                  </div>
                );
              })}
            </div>
          </div>
        </div>

        {/* Clear Medical Research Disclaimer Box */}
        <div className="mt-4 pt-4 border-t border-[#E3EAE9] flex items-start gap-3 bg-[#F4F7F5] p-3 text-[11px] text-[#526C7A]">
          <ShieldAlert className="w-4 h-4 text-[#D62839] shrink-0 mt-0.5" />
          <p className="leading-relaxed">
            <strong className="text-[#003153]">Research and Educational Disclaimer:</strong> NeuroScan AI is designed to demonstrate computer vision and convolutional feature extraction on brain MRI scans. It is not an FDA-cleared diagnostic medical device and must never be used as a substitute for professional clinical judgment, biopsy confirmation, or formal radiologist consultation.
          </p>
        </div>
      </div>

      {/* Embedded Saliency Heatmap Comparison Slider */}
      <GradCamHeatmapViewer
        originalImageUrl={result.previewUrl}
        prediction={result.prediction}
        confidence={result.confidence}
        filename={result.filename}
      />
    </div>
  );
}
